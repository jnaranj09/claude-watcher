// GOALS.md (spec 2026-10-29): a goal with `Save to GOALS.md` on is kept, with its tasks, in
// `<goal folder>/GOALS.md`, so the plan is committed with the project. Export only: the app writes
// the file and never reads it back, except its first line, which says the app made it.
//
// The goals store calls `afterChange` from its one emit path, after every change to goals or tasks
// whatever its source (a write of only the session lineage or the planner records does not emit);
// a folder is written only when its rendered text changed, so a link or a `/clear` rebind (not in
// the file) writes nothing. A file without the header is never written or removed, and a
// missing folder is never created. Problems live in memory, per folder; the store folds them into
// `GoalsView.fileProblems`. NEVER log a path, a goal name or a task title — codes only.
import { randomUUID } from 'node:crypto'
import {
  closeSync,
  constants,
  lstatSync,
  openSync,
  readFileSync,
  renameSync,
  rmSync,
  statSync,
  writeFileSync
} from 'node:fs'
import { join } from 'node:path'
import type { Goal, GoalFileProblem, GoalsFileProblemCode, Task } from '../../shared/schemas/goal'

export const GOALS_FILE_NAME = 'GOALS.md'
export const GOALS_FILE_HEADER = '<!-- Generated by claude-watcher. Edits here are overwritten. -->'
const TMP_SUFFIX = '.claude-watcher-tmp'
const LOG_PREFIX = '[claude-watcher][goals]'

const LOG_CODE: Record<GoalsFileProblemCode, string> = {
  goals_file_not_ours: 'goals_file_not_ours',
  folder_missing: 'goals_file_folder_missing',
  goals_file_write_failed: 'goals_file_write_failed'
}

export interface GoalsSnapshot {
  goals: readonly Goal[]
  tasks: readonly Task[]
}

function savingGoals(folder: string, snap: GoalsSnapshot): Goal[] {
  return snap.goals
    .filter((g) => g.saveToFile && g.defaultCwd === folder)
    .sort((a, b) => a.createdAt - b.createdAt)
}

/** One folder's text, or null when no goal with `saveToFile` uses that folder. Pure. */
export function renderGoalsFile(folder: string, snap: GoalsSnapshot): string | null {
  const goals = savingGoals(folder, snap)
  if (goals.length === 0) return null
  const lines = [GOALS_FILE_HEADER, '', '# Goals']
  for (const goal of goals) {
    lines.push('', `## ${goal.name}`)
    const tasks = snap.tasks.filter((t) => t.goalId === goal.id)
    if (tasks.length > 0) lines.push('')
    for (const task of tasks) lines.push(`- [${task.status === 'done' ? 'x' : ' '}] ${task.title}`)
  }
  return `${lines.join('\n')}\n`
}

/** Every folder a saving goal uses. */
function savingFolders(snap: GoalsSnapshot): Set<string> {
  const folders = new Set<string>()
  for (const g of snap.goals) if (g.saveToFile && g.defaultCwd !== null) folders.add(g.defaultCwd)
  return folders
}

export interface GoalsFileFs {
  isDirectory(path: string): boolean
  /** null = no such file; '' = a path that is not a regular file (a link, a folder). */
  readText(path: string): string | null
  /** Creates `path`; throws when anything (a link included) is already there. */
  writeText(path: string, text: string): void
  rename(from: string, to: string): void
  remove(path: string): void
}

export interface GoalsFileExporter {
  /** After every store change: rewrite each folder whose text changed. */
  afterChange(before: GoalsSnapshot, after: GoalsSnapshot): void
  /** App start: record problems only, never write (no write without an operator action). */
  check(snap: GoalsSnapshot): void
  /** `Save to GOALS.md` turned on, or `Try again`: sync that folder whatever changed. */
  rewrite(folder: string, snap: GoalsSnapshot): void
  /** One entry per saving goal whose folder has a problem. */
  problems(snap: GoalsSnapshot): GoalFileProblem[]
}

export function createGoalsFileExporter(deps: {
  fs: GoalsFileFs
  log(message: string): void
  /** A problem no saving goal is left to show (its last goal was deleted, moved or turned off). */
  reportOrphan(): void
}): GoalsFileExporter {
  const { fs } = deps
  const problemOf = new Map<string, GoalsFileProblemCode>()

  function isOurs(text: string): boolean {
    return text.split('\n', 1)[0] === GOALS_FILE_HEADER
  }

  /** What is wrong with writing in `folder` now, or null. */
  function obstacle(folder: string): GoalsFileProblemCode | null {
    if (!fs.isDirectory(folder)) return 'folder_missing'
    const current = fs.readText(join(folder, GOALS_FILE_NAME))
    return current !== null && !isOurs(current) ? 'goals_file_not_ours' : null
  }

  /** Write `text` through a temp file; on failure the temp file goes and the error rethrows.
   *  The temp name is random and `writeText` creates it new: a cloned project cannot plant a
   *  link at a name it can guess and have the write land outside the folder. */
  function writeAtomic(file: string, text: string): void {
    const tmp = `${file}.${randomUUID()}${TMP_SUFFIX}`
    try {
      fs.writeText(tmp, text)
      fs.rename(tmp, file)
    } catch (err) {
      try {
        fs.remove(tmp)
      } catch {
        deps.log(`${LOG_PREFIX} code=goals_file_tmp_left`)
      }
      throw err
    }
  }

  /** Make `folder`'s file say `text` (null = no file). Returns the problem, or null. */
  function write(folder: string, text: string | null): GoalsFileProblemCode | null {
    const file = join(folder, GOALS_FILE_NAME)
    try {
      // Nothing left to say in a folder that is gone: its file is gone with it.
      if (text === null && !fs.isDirectory(folder)) return null
      const blocked = obstacle(folder)
      // A file the app did not make is never removed, and leaving it is not a failure.
      if (blocked === 'goals_file_not_ours' && text === null) return null
      if (blocked !== null) return blocked
      if (fs.readText(file) === text) return null
      if (text === null) fs.remove(file)
      else writeAtomic(file, text)
      return null
    } catch {
      return 'goals_file_write_failed'
    }
  }

  function record(folder: string, code: GoalsFileProblemCode | null, after: GoalsSnapshot): void {
    if (code === null) {
      problemOf.delete(folder)
      return
    }
    deps.log(`${LOG_PREFIX} code=${LOG_CODE[code]}`)
    if (savingFolders(after).has(folder)) {
      problemOf.set(folder, code)
      return
    }
    problemOf.delete(folder)
    deps.reportOrphan()
  }

  function sync(folder: string, after: GoalsSnapshot): void {
    record(folder, write(folder, renderGoalsFile(folder, after)), after)
  }

  return {
    afterChange(before, after) {
      const folders = new Set([...savingFolders(before), ...savingFolders(after)])
      for (const folder of folders) {
        if (renderGoalsFile(folder, before) !== renderGoalsFile(folder, after)) sync(folder, after)
      }
    },
    check(snap) {
      for (const folder of savingFolders(snap)) {
        let code: GoalsFileProblemCode | null
        try {
          code = obstacle(folder)
        } catch {
          code = 'goals_file_write_failed'
        }
        if (code === null) problemOf.delete(folder)
        else record(folder, code, snap)
      }
    },
    rewrite(folder, snap) {
      sync(folder, snap)
    },
    problems(snap) {
      return snap.goals.flatMap((g) => {
        const code = g.saveToFile && g.defaultCwd !== null ? problemOf.get(g.defaultCwd) : undefined
        return code === undefined ? [] : [{ goalId: g.id, code }]
      })
    }
  }
}

/** The real fs, synchronous: the files are small and the store's emit is synchronous. */
export const nodeGoalsFileFs: GoalsFileFs = {
  isDirectory(path) {
    // A yes/no check: a path that cannot be stat'ed is not a folder we can write in.
    try {
      return statSync(path).isDirectory()
    } catch {
      return false
    }
  },
  readText(path) {
    try {
      // A link or any other non-file is not a file the app made: '' has no header, so the caller
      // sees `goals_file_not_ours` and never writes or removes it.
      if (!lstatSync(path).isFile()) return ''
      return readFileSync(path, 'utf8')
    } catch (err) {
      if (err instanceof Error && 'code' in err && err.code === 'ENOENT') return null
      throw err
    }
  },
  writeText(path, text) {
    // Create only: never open a file or link that is already there.
    const flags = constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW
    const fd = openSync(path, flags, 0o644)
    try {
      writeFileSync(fd, text, 'utf8')
    } finally {
      closeSync(fd)
    }
  },
  rename(from, to) {
    renameSync(from, to)
  },
  remove(path) {
    rmSync(path, { force: true })
  }
}
